#!/usr/bin/env python3
"""Generate deterministic SQL Server seed data for the AeroMRO-EDQSG benchmark."""

from __future__ import annotations

import argparse
import hashlib
import random
from dataclasses import dataclass
from datetime import date, datetime, timedelta
from pathlib import Path
from typing import Any, Iterable


@dataclass(frozen=True)
class Scale:
    manufacturers: int
    aircraft_types: int
    aircraft: int
    suppliers: int
    parts: int
    instances: int
    purchase_orders: int
    work_orders: int


SCALES = {
    "small": Scale(6, 4, 10, 8, 80, 300, 30, 20),
    "medium": Scale(12, 8, 50, 25, 800, 8000, 500, 300),
    "large": Scale(20, 12, 200, 60, 5000, 100000, 5000, 2500),
}


def q(value: Any) -> str:
    if value is None:
        return "NULL"
    if isinstance(value, bool):
        return "1" if value else "0"
    if isinstance(value, (int, float)):
        return str(value)
    if isinstance(value, datetime):
        return "N'" + value.strftime("%Y-%m-%dT%H:%M:%S") + "'"
    if isinstance(value, date):
        return "N'" + value.isoformat() + "'"
    text = str(value).replace("'", "''")
    return "N'" + text + "'"


def emit_insert(lines: list[str], table: str, columns: list[str], rows: Iterable[tuple[Any, ...]], batch: int = 500) -> None:
    rows = list(rows)
    if not rows:
        return
    col_sql = ", ".join(f"[{c}]" for c in columns)
    for start in range(0, len(rows), batch):
        chunk = rows[start : start + batch]
        values = ",\n".join("(" + ", ".join(q(v) for v in row) + ")" for row in chunk)
        lines.append(f"INSERT INTO {table} ({col_sql}) VALUES\n{values};\nGO\n")


def emit_identity(lines: list[str], table: str, columns: list[str], rows: Iterable[tuple[Any, ...]]) -> None:
    lines.append(f"SET IDENTITY_INSERT {table} ON;\nGO\n")
    emit_insert(lines, table, columns, rows)
    lines.append(f"SET IDENTITY_INSERT {table} OFF;\nGO\n")


def generate(scale_name: str, seed: int, output: Path) -> None:
    cfg = SCALES[scale_name]
    rng = random.Random(seed)
    today = date(2026, 7, 24)
    now = datetime(2026, 7, 24, 12, 0, 0)
    lines = [
        "/* Generated by tools/generate_dataset.py. */\n",
        "USE AeroMRO_EDQSG;\nGO\nSET NOCOUNT ON;\nSET XACT_ABORT ON;\nGO\n",
    ]

    manufacturers = []
    for i in range(1, cfg.manufacturers + 1):
        manufacturers.append((i, f"MFR{i:03d}", f"航空制造商{i:03d}", ["CN", "US", "FR", "DE", "GB", "CA"][i % 6], 1, now, "generator", now, "generator"))
    emit_identity(lines, "aero.manufacturer", ["manufacturer_id", "manufacturer_code", "manufacturer_name", "country_code", "active_flag", "created_at", "created_by", "updated_at", "updated_by"], manufacturers)

    ata_rows = [
        ("2100", "空调系统", None, 1, now, "generator", now, "generator"),
        ("2400", "电源系统", None, 1, now, "generator", now, "generator"),
        ("2700", "飞行操纵", None, 1, now, "generator", now, "generator"),
        ("2800", "燃油系统", None, 1, now, "generator", now, "generator"),
        ("3200", "起落架", None, 1, now, "generator", now, "generator"),
        ("4900", "辅助动力装置", None, 1, now, "generator", now, "generator"),
        ("7200", "发动机", None, 1, now, "generator", now, "generator"),
        ("7900", "滑油系统", None, 1, now, "generator", now, "generator"),
    ]
    emit_insert(lines, "aero.ata_chapter", ["ata_code", "chapter_name", "parent_ata_code", "active_flag", "created_at", "created_by", "updated_at", "updated_by"], ata_rows)

    aircraft_types = []
    for i in range(1, cfg.aircraft_types + 1):
        mfr = ((i - 1) % cfg.manufacturers) + 1
        aircraft_types.append((i, f"TYPE-{i:02d}", mfr, f"Model-{i:02d}", f"Series-{1 + i % 3}", 1, now, "generator", now, "generator"))
    emit_identity(lines, "aero.aircraft_type", ["aircraft_type_id", "type_code", "manufacturer_id", "model_name", "series_name", "active_flag", "created_at", "created_by", "updated_at", "updated_by"], aircraft_types)

    aircraft = []
    for i in range(1, cfg.aircraft + 1):
        aircraft.append((i, f"B-{7000+i}", f"ACSN-{i:06d}", ((i - 1) % cfg.aircraft_types) + 1, "OP-A", "ACTIVE", today - timedelta(days=1000 + i * 17), now, "generator", now, "generator"))
    emit_identity(lines, "aero.aircraft", ["aircraft_id", "registration_no", "aircraft_serial_no", "aircraft_type_id", "operator_code", "aircraft_status", "delivery_date", "created_at", "created_by", "updated_at", "updated_by"], aircraft)

    suppliers = []
    for i in range(1, cfg.suppliers + 1):
        suppliers.append((i, f"SUP{i:04d}", f"航材供应商{i:04d}", f"APP-{i:05d}", today + timedelta(days=365 + i), round(75 + rng.random() * 24, 2), "APPROVED", now, "generator", now, "generator"))
    emit_identity(lines, "aero.supplier", ["supplier_id", "supplier_code", "supplier_name", "approval_no", "approval_valid_to", "supplier_rating", "supplier_status", "created_at", "created_by", "updated_at", "updated_by"], suppliers)

    ata_codes = [r[0] for r in ata_rows]
    parts = []
    part_info: dict[int, dict[str, Any]] = {}
    for i in range(1, cfg.parts + 1):
        serialized = i % 3 != 0
        batch = not serialized
        life = serialized and i % 4 == 0
        repairable = serialized and i % 5 != 0
        shelf_days = 730 if (not serialized and i % 2 == 0) else None
        part_no = f"PN-{i:06d}"
        part_name = f"航空器材-{i:06d}"
        parts.append((i, part_no, part_name, ((i - 1) % cfg.manufacturers) + 1, ata_codes[i % len(ata_codes)], "EA", serialized, batch, life, repairable, shelf_days, "ACTIVE", now, "generator", now, "generator"))
        part_info[i] = {"part_number": part_no, "part_name": part_name, "serialized": serialized, "life": life, "shelf_days": shelf_days}
    emit_identity(lines, "aero.part_master", ["part_id", "part_number", "part_name", "manufacturer_id", "ata_code", "unit_code", "serialized_flag", "batch_control_flag", "life_limited_flag", "repairable_flag", "shelf_life_days", "active_status", "created_at", "created_by", "updated_at", "updated_by"], parts)

    applicability = []
    for part_id in range(1, cfg.parts + 1):
        t1 = ((part_id - 1) % cfg.aircraft_types) + 1
        applicability.append((part_id, t1, today - timedelta(days=1000), None, "标准适用关系", now, "generator"))
        if cfg.aircraft_types > 1 and part_id % 5 == 0:
            t2 = (t1 % cfg.aircraft_types) + 1
            applicability.append((part_id, t2, today - timedelta(days=500), None, "扩展适用关系", now, "generator"))
    emit_insert(lines, "aero.part_applicability", ["part_id", "aircraft_type_id", "effective_from", "effective_to", "applicability_note", "created_at", "created_by"], applicability)

    alternatives = []
    alt_id = 1
    for base in range(1, cfg.parts, 20):
        if base + 1 <= cfg.parts:
            alternatives.append((alt_id, base, base + 1, "ALTERNATE", today - timedelta(days=300), None, now, "generator")); alt_id += 1
    emit_identity(lines, "aero.part_alternative", ["part_alternative_id", "base_part_id", "alternative_part_id", "relation_type", "effective_from", "effective_to", "created_at", "created_by"], alternatives)

    warehouses = [(1, "WH-NORTH", "北区航材库", "ORG-A", 1, now, "generator", now, "generator"), (2, "WH-SOUTH", "南区航材库", "ORG-A", 1, now, "generator", now, "generator")]
    emit_identity(lines, "aero.warehouse", ["warehouse_id", "warehouse_code", "warehouse_name", "organization_code", "active_flag", "created_at", "created_by", "updated_at", "updated_by"], warehouses)
    locations = []
    loc_id = 1
    for wh in (1, 2):
        for idx, env in enumerate(("NORMAL", "DRY", "CONTROLLED", "COLD"), start=1):
            locations.append((loc_id, wh, f"{chr(64+idx)}-{wh:02d}-{idx:02d}", env, None, 0, 1, now, "generator", now, "generator")); loc_id += 1
    emit_identity(lines, "aero.storage_location", ["location_id", "warehouse_id", "location_code", "environment_class", "hazardous_class", "quarantine_flag", "active_flag", "created_at", "created_by", "updated_at", "updated_by"], locations)

    instances = []
    balances = []
    txs = []
    instance_part: dict[int, int] = {}
    for instance_id in range(1, cfg.instances + 1):
        part_id = ((instance_id - 1) % cfg.parts) + 1
        info = part_info[part_id]
        location_id = ((instance_id - 1) % len(locations)) + 1
        production = today - timedelta(days=120 + (instance_id % 900))
        expiry = production + timedelta(days=info["shelf_days"]) if info["shelf_days"] else None
        serial = f"SN-{part_id:06d}-{instance_id:08d}" if info["serialized"] else None
        batch_no = None if info["serialized"] else f"LOT-{part_id:06d}-{1 + instance_id // 10:05d}"
        qty = 1 if info["serialized"] else 10 + instance_id % 40
        received = now - timedelta(days=30 + instance_id % 300)
        instances.append((instance_id, part_id, serial, batch_no, production, expiry, "SERVICEABLE", location_id, qty, received, now, "generator", now, "generator"))
        balances.append((instance_id, location_id, qty, 0, now, "generator"))
        txs.append((instance_id, instance_id, part_id, "RECEIPT", None, location_id, qty, received, "RECEIPT", 1 + (instance_id - 1) % max(1, cfg.purchase_orders), "generator", info["part_number"], info["part_name"], received, "generator"))
        instance_part[instance_id] = part_id
    emit_identity(lines, "aero.part_instance", ["part_instance_id", "part_id", "serial_number", "batch_number", "production_date", "expiry_date", "condition_status", "current_location_id", "on_hand_quantity", "received_at", "created_at", "created_by", "updated_at", "updated_by"], instances)
    emit_insert(lines, "aero.inventory_balance", ["part_instance_id", "location_id", "available_quantity", "frozen_quantity", "balance_updated_at", "updated_by"], balances)

    purchase_orders = []
    po_lines = []
    receipts = []
    receipt_lines = []
    certificates = []
    inspections = []
    line_id = receipt_line_id = certificate_id = inspection_id = 1
    instances_by_po: dict[int, list[int]] = {i: [] for i in range(1, cfg.purchase_orders + 1)}
    for instance_id in range(1, cfg.instances + 1):
        instances_by_po[1 + (instance_id - 1) % cfg.purchase_orders].append(instance_id)
    for po_id in range(1, cfg.purchase_orders + 1):
        order_date = today - timedelta(days=400 - po_id)
        purchase_orders.append((po_id, f"PO-{po_id:07d}", 1 + (po_id - 1) % cfg.suppliers, order_date, "CNY", "CLOSED", f"buyer{po_id%5}", now, "generator", now, "generator"))
        receipt_id = po_id
        receipts.append((receipt_id, f"RCV-{receipt_id:07d}", po_id, datetime.combine(order_date + timedelta(days=20), datetime.min.time()), f"receiver{po_id%4}", "ACCEPTED", now, "generator", now, "generator"))
        for line_no, instance_id in enumerate(instances_by_po[po_id], start=1):
            part_id = instance_part[instance_id]
            qty = instances[instance_id - 1][8]
            po_lines.append((line_id, po_id, line_no, part_id, qty, round(100 + rng.random() * 50000, 2), order_date + timedelta(days=30), qty, now, "generator"))
            cert_no = f"CERT-{instance_id:09d}"
            receipt_lines.append((receipt_line_id, receipt_id, line_id, instance_id, qty, 1, cert_no, now, "generator"))
            digest = hashlib.sha256(f"{seed}:{instance_id}".encode()).hexdigest()
            certificates.append((certificate_id, instance_id, "COC", cert_no, "Benchmark Issuer", order_date + timedelta(days=15), None, digest, "VERIFIED", now, "generator"))
            inspections.append((inspection_id, receipt_line_id, instance_id, "PASS", datetime.combine(order_date + timedelta(days=21), datetime.min.time()), f"inspector{po_id%3}", None, now, "generator"))
            line_id += 1; receipt_line_id += 1; certificate_id += 1; inspection_id += 1
    emit_identity(lines, "aero.purchase_order", ["purchase_order_id", "purchase_order_no", "supplier_id", "order_date", "currency_code", "order_status", "requested_by", "created_at", "created_by", "updated_at", "updated_by"], purchase_orders)
    emit_identity(lines, "aero.purchase_order_line", ["purchase_order_line_id", "purchase_order_id", "line_no", "part_id", "ordered_quantity", "unit_price", "required_date", "received_quantity", "created_at", "created_by"], po_lines)
    emit_identity(lines, "aero.receipt", ["receipt_id", "receipt_no", "purchase_order_id", "received_at", "received_by", "receipt_status", "created_at", "created_by", "updated_at", "updated_by"], receipts)
    emit_identity(lines, "aero.receipt_line", ["receipt_line_id", "receipt_id", "purchase_order_line_id", "part_instance_id", "received_quantity", "certificate_required_flag", "certificate_no_received", "created_at", "created_by"], receipt_lines)
    emit_identity(lines, "aero.certificate_document", ["certificate_document_id", "part_instance_id", "certificate_type", "certificate_no", "issuer_name", "issue_date", "valid_to", "document_hash", "verification_status", "created_at", "created_by"], certificates)
    emit_identity(lines, "aero.inspection_record", ["inspection_record_id", "receipt_line_id", "part_instance_id", "inspection_result", "inspected_at", "inspector_id", "defect_note", "created_at", "created_by"], inspections)
    emit_identity(lines, "aero.inventory_transaction", ["inventory_transaction_id", "part_instance_id", "part_id", "transaction_type", "source_location_id", "target_location_id", "quantity", "transaction_time", "reference_type", "reference_id", "operator_id", "part_number_snapshot", "part_name_snapshot", "created_at", "created_by"], txs)

    work_orders = []
    install_events = []
    usage = []
    life_limits = []
    event_id = usage_id = life_id = 1
    serialized_instances = [i for i in range(1, cfg.instances + 1) if part_info[instance_part[i]]["serialized"]]
    for wo_id in range(1, cfg.work_orders + 1):
        opened = now - timedelta(days=100 - wo_id)
        closed = opened + timedelta(hours=8)
        aircraft_id = 1 + (wo_id - 1) % cfg.aircraft
        work_orders.append((wo_id, f"WO-{wo_id:07d}", aircraft_id, "SCHEDULED", opened, closed, "CLOSED", now, "generator", now, "generator"))
        instance_id = serialized_instances[(wo_id - 1) % len(serialized_instances)]
        install_events.append((event_id, wo_id, aircraft_id, instance_id, f"POS-{1+wo_id%8}", opened + timedelta(hours=1), closed - timedelta(hours=1), "计划拆换", now, "generator")); event_id += 1
        for n in range(2):
            snap_at = opened + timedelta(hours=n * 3)
            hours = round(100 + wo_id * 10 + n * 3.5, 2)
            cycles = 50 + wo_id * 3 + n
            usage.append((usage_id, instance_id, snap_at, hours, cycles, "BENCHMARK", now, "generator")); usage_id += 1
        if part_info[instance_part[instance_id]]["life"]:
            used = min(9000, 100 + wo_id * 10)
            life_limits.append((life_id, instance_id, "HOURS", 10000, used, closed, now, "generator")); life_id += 1
    emit_identity(lines, "aero.maintenance_work_order", ["maintenance_work_order_id", "work_order_no", "aircraft_id", "task_type", "opened_at", "closed_at", "work_order_status", "created_at", "created_by", "updated_at", "updated_by"], work_orders)
    emit_identity(lines, "aero.install_remove_event", ["install_remove_event_id", "maintenance_work_order_id", "aircraft_id", "part_instance_id", "installation_position", "installed_at", "removed_at", "removal_reason", "created_at", "created_by"], install_events)
    emit_identity(lines, "aero.usage_snapshot", ["usage_snapshot_id", "part_instance_id", "snapshot_at", "flight_hours", "flight_cycles", "source_system", "created_at", "created_by"], usage)
    emit_identity(lines, "aero.life_limit_control", ["life_limit_control_id", "part_instance_id", "limit_type", "limit_value", "used_value", "evaluated_at", "created_at", "created_by"], life_limits)

    repair_rows = []
    scrap_rows = []
    for rid, instance_id in enumerate(serialized_instances[: max(1, min(5, len(serialized_instances)))], start=1):
        repair_rows.append((rid, f"RO-{rid:07d}", instance_id, 1 + (rid - 1) % cfg.suppliers, now - timedelta(days=60), now - timedelta(days=30), "RETURNED", "修理合格", now, "generator", now, "generator"))
    emit_identity(lines, "aero.repair_order", ["repair_order_id", "repair_order_no", "part_instance_id", "supplier_id", "sent_at", "returned_at", "repair_status", "repair_result", "created_at", "created_by", "updated_at", "updated_by"], repair_rows)
    # Keep scrap empty in the clean small seed; defect scenarios can create it.

    relationship_controls = [
        (
            "REL-TX-RECEIPT", "aero.inventory_transaction", "reference_id",
            "aero.receipt", "receipt_id", "many_to_one", "high", False,
            "application_validation,scheduled_audit", 0.98, 0.95, 0.98, True,
            "多态来源关系无法使用单一物理外键", "ARCH-REL-001",
            "航材库存与接口联合责任组", date(2027, 7, 1), 0.0, 0.75,
        ),
        (
            "REL-TX-PART", "aero.inventory_transaction", "part_id",
            "aero.part_master", "part_id", "many_to_one", "critical", False,
            "scheduled_audit", 1.0, 0.99, 0.99, False, None, None,
            "航材库存系统组", None, 0.0, 0.75,
        ),
        (
            "REL-RECEIPT-INSTANCE", "aero.receipt_line", "part_instance_id",
            "aero.part_instance", "part_instance_id", "many_to_one", "critical", False,
            "scheduled_audit", 1.0, 0.99, 0.99, False, None, None,
            "航材收货与质量检验组", None, 0.0, 0.75,
        ),
    ]
    emit_insert(
        lines,
        "dq.relationship_control_registry",
        [
            "relationship_id", "child_table", "child_columns", "parent_table",
            "parent_columns", "cardinality", "criticality", "physical_fk_required",
            "enforcement_modes", "control_coverage", "control_reliability",
            "operating_effectiveness", "exception_approved", "exception_reason",
            "performance_evidence_id", "owner_name", "review_due_date",
            "maximum_orphan_rate", "minimum_control_score",
        ],
        relationship_controls,
    )

    rules = [
        ("DQ1-RECEIPT-CERT", "DATA", "DQ1", "应附证书的收货行证书号必填", "certificate_required_flag=0 OR certificate_no_received IS NOT NULL", 0.9, 1, 1, now),
        ("DQ4-PART-SERIAL", "DATA", "DQ4", "序列化件序列号唯一", "part_id+serial_number unique", 1.0, 1, 1, now),
        ("DQ6-TX-PART", "COUPLING", "DQ6", "库存事务必须引用存在的器材", "inventory_transaction.part_id -> part_master.part_id", 1.0, 1, 1, now),
        ("SG3-KEYS", "SCHEMA", "SG3", "关键表主键和业务唯一约束完整", "metadata constraint coverage", 1.0, 1, 1, now),
    ]
    emit_insert(lines, "dq.quality_rule", ["rule_id", "rule_domain", "indicator_id", "rule_name", "rule_expression", "severity", "critical_flag", "active_flag", "created_at"], rules)

    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("".join(lines), encoding="utf-8")
    print(f"generated {output} ({output.stat().st_size/1024/1024:.2f} MiB)")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--scale", choices=SCALES, default="small")
    parser.add_argument("--seed", type=int, default=20260724)
    parser.add_argument("--output", type=Path, default=Path("data/02_seed_clean_small.sql"))
    args = parser.parse_args()
    generate(args.scale, args.seed, args.output)


if __name__ == "__main__":
    main()
