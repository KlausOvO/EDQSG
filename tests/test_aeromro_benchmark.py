from __future__ import annotations

import subprocess
import sys
from pathlib import Path


def test_aeromro_small_dataset_generator(tmp_path):
    root = Path(__file__).resolve().parents[1]
    generator = root / "benchmark" / "aeromro" / "tools" / "generate_dataset.py"
    output = tmp_path / "seed.sql"
    subprocess.run(
        [sys.executable, str(generator), "--scale", "small", "--output", str(output)],
        check=True,
    )
    text = output.read_text(encoding="utf-8")
    assert "USE AeroMRO_EDQSG" in text
    assert "INSERT aero.part_master" in text
    assert "INSERT aero.part_instance" in text
    assert "INSERT aero.inventory_transaction" in text
    assert "Generated by tools/generate_dataset.py" in text
    assert "INSERT INTO dq.quality_rule" in text
    assert "INSERT INTO dq.relationship_control_registry" in text


def test_benchmark_has_dual_domain_and_propagation_scenarios():
    root = Path(__file__).resolve().parents[1]
    benchmark = root / "benchmark" / "aeromro"
    names = {item.name for item in (benchmark / "scenarios").glob("*.sql")}
    workloads = {item.name for item in (benchmark / "workload").glob("*.sql")}
    assert "DQ1_missing_required_certificate.sql" in names
    assert "SG3_controlled_no_physical_fk.sql" in names
    assert "SG3_uncontrolled_no_physical_fk.sql" in names
    assert "W_SG3_orphan_part_propagation.sql" in workloads
    assert "W_SG3_controlled_relation_valid_workload.sql" in workloads
    catalog = (benchmark / "ground_truth" / "defect_catalog.csv").read_text(
        encoding="utf-8"
    )
    assert "COUPLING" in catalog
    assert "P-SG3-DQ6-ORPHAN-PART" in catalog
    assert "SG3-CONTROLLED-NO-FK" in catalog
    assert "SG3-UNCONTROLLED-NO-FK" in catalog
    matrix = (benchmark / "ground_truth" / "relationship_control_experiments.csv").read_text(
        encoding="utf-8-sig"
    )
    assert "REL-CONTROLLED-NO-FK" in matrix
    assert "REL-UNCONTROLLED-NO-FK" in matrix
